bool check_charset(const char *charset);
uint32_t get_unicode_point(unsigned char c, int charset_type);

int main(int const argc, char *argv[]) {
    if (argc != 4) {
        printf("Error: wrong number of arguments\n");
        return ERROR_EXIT;
    }

    if (argv[ENCODING_CHARSET_INDEX] == NULL || !check_charset(argv[ENCODING_CHARSET_INDEX])) {
        printf("Error: wrong character encoding\n");
        return ERROR_EXIT;
    }

    FILE * const fileIn = fopen(argv[FILE_NAME_INPUT_INDEX], "rb");
    if (fileIn == NULL) {
        printf("Error: could not open input file\n");
        return ERROR_EXIT;
    }

    FILE * const fileOut = fopen(argv[FILE_NAME_OUTPUT_INDEX], "wb");
    if (fileOut == NULL) {
        printf("Error: could not open output file\n");
        return ERROR_EXIT;
    }


    int charset_type = -1;
    if (strcmp(argv[ENCODING_CHARSET_INDEX], CP_1251) == 0) {
        charset_type = CP_1251_TYPE;
    }

    if (strcmp(argv[ENCODING_CHARSET_INDEX], KOI8_R) == 0) {
        charset_type = KOI8_R_TYPE;
    }

    if (strcmp(argv[ENCODING_CHARSET_INDEX], ISO_8859_5) == 0) {
        charset_type = ISO_8859_5_TYPE;
    }

    if (charset_type == -1) {
        printf("Error: unsupported charset\n");
        return ERROR_EXIT;
    }

    int c;
    unsigned char data[2];
    int exit_code = 0;
    while ((c = fgetc(fileIn)) != EOF) {
        const uint32_t unicode_point = get_unicode_point(c, charset_type);

        if (unicode_point == 0xFFFFFFFF) {
            printf("Error: could not get unicode point from CP-1251\n");
            exit_code = ERROR_EXIT;
            break;
        }

        if (unicode_point <= 0x7F ) { // ASCII table
            const unsigned char byte = unicode_point;
            if (fputc(byte, fileOut) == EOF) {
                printf("Error: could not write to output file\n");
                exit_code = ERROR_EXIT;
                break;
            }
        }

        if (unicode_point <= 0x7FF ) {
            data[0] = 0xC0 | (unicode_point >> 6);
            data[1] = 0x80 | (unicode_point & 0x3F);
            const size_t n = fwrite(data, 1, sizeof data, fileOut);
            if (n != sizeof data) {
                printf("Error: could not write to output file\n");
                exit_code = ERROR_EXIT;
                break;
            }
        }
    }

    fclose(fileIn);
    fclose(fileOut);
    printf("Encoding is done...\n");

    return exit_code;
}

bool check_charset(const char *charset) {
    if (strcmp(charset, CP_1251) == 0) {
        return true;
    }

    if (strcmp(charset, KOI8_R) == 0) {
        return true;
    }

    if (strcmp(charset, ISO_8859_5) == 0) {
        return true;
    }

    return false;
}

uint32_t get_unicode_point(const unsigned char c, const int charset_type) {
    if (c < ASCII_OFFSET) {
        return c;
    }

    switch (charset_type) {
        case CP_1251_TYPE:
            return codepoints_cp1251[c - ASCII_OFFSET];

        case KOI8_R_TYPE:
            return codepoints_koi8r[c - ASCII_OFFSET];

        default : // ISO_8859_5_TYPE
            return codepoints_iso88595[c - ASCII_OFFSET];
    }
}
